// node tools/sculpt/build.mjs [name ...]  -> data/models.js (gzip + base64 per model; decoded in the game at boot)
import fs from 'fs'; import path from 'path'; import zlib from 'zlib'; import { fileURLToPath } from 'url';
import { sculpt, pack } from './mesh.mjs';
const here = path.dirname(fileURLToPath(import.meta.url)), root = path.join(here, '../..');
const SK = JSON.parse(fs.readFileSync(path.join(here, 'skeletons.json'), 'utf8'));
const cacheDir = path.join(here, 'cache'); fs.mkdirSync(cacheDir, { recursive: true });
const only = process.argv.slice(2);
const list = fs.readdirSync(path.join(here, 'models')).filter((f) => f.endsWith('.mjs') && !f.startsWith('_')).map((f) => f.slice(0, -4));
for (const name of list) {
  if (only.length && !only.includes(name)) continue;
  const t0 = Date.now(); const def = (await import(path.join(here, 'models', name + '.mjs'))).default(SK);
  const m = await sculpt(def); const bin = pack(m);
  fs.writeFileSync(path.join(cacheDir, name + '.bin'), bin);
  console.log(name, JSON.stringify(m.info), ((Date.now() - t0) / 1000).toFixed(1) + 's', (bin.length / 1024).toFixed(0) + 'KB');
}
// assemble: models already in data/models.js are kept (the cache folder is not committed, so a fresh clone that
// rebuilds one model must not drop the others); every cached model replaces its old entry
const outPath = path.join(root, 'data/models.js'), ent = new Map();
if (fs.existsSync(outPath)) for (const m of fs.readFileSync(outPath, 'utf8').matchAll(/(?:^|{)(\w+):"([A-Za-z0-9+/=]+)",$/gm)) ent.set(m[1], m[2]);
for (const f of fs.readdirSync(cacheDir).filter((f) => f.endsWith('.bin'))) ent.set(f.slice(0, -4), zlib.gzipSync(fs.readFileSync(path.join(cacheDir, f)), { level: 9 }).toString('base64'));
let out = '// generated by tools/sculpt/build.mjs — sculpted character meshes (gzip+base64)\nconst MODELS={';
for (const k of [...ent.keys()].sort()) out += k + ':"' + ent.get(k) + '",\n';
out += '};\n'; fs.writeFileSync(outPath, out);
console.log('data/models.js', (out.length / 1024).toFixed(0) + 'KB');
